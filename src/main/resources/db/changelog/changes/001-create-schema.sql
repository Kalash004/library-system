--changeset anton:001-author
CREATE TABLE author (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    CONSTRAINT uk_author_email UNIQUE (email)
);
--rollback DROP TABLE author;

--changeset anton:001-publisher
CREATE TABLE publisher (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL
);
--rollback DROP TABLE publisher;

--changeset anton:001-contract
CREATE TABLE contract (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    BIGINT NOT NULL REFERENCES author (id),
    publisher_id BIGINT NOT NULL REFERENCES publisher (id),
    signed_at    DATE   NOT NULL,
    CONSTRAINT uk_contract_author_publisher UNIQUE (author_id, publisher_id)
);
-- the unique constraint already indexes (author_id, publisher_id); PostgreSQL doesn't index FKs by itself
CREATE INDEX ix_contract_publisher ON contract (publisher_id);
--rollback DROP TABLE contract;

--changeset anton:001-book
CREATE TABLE book (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn             VARCHAR(17)  NOT NULL,
    title            VARCHAR(255) NOT NULL,
    publication_date DATE         NOT NULL,
    genre            VARCHAR(30)  NOT NULL,
    publisher_id     BIGINT       NOT NULL REFERENCES publisher (id),
    CONSTRAINT uk_book_isbn UNIQUE (isbn)
);
CREATE INDEX ix_book_publisher ON book (publisher_id);
--rollback DROP TABLE book;

--changeset anton:001-authorship
CREATE TABLE authorship (
    book_id   BIGINT NOT NULL REFERENCES book (id),
    author_id BIGINT NOT NULL REFERENCES author (id),
    PRIMARY KEY (book_id, author_id)
);
CREATE INDEX ix_authorship_author ON authorship (author_id);
--rollback DROP TABLE authorship;

--changeset anton:001-library
CREATE TABLE library (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL
);
--rollback DROP TABLE library;

--changeset anton:001-book-copy
CREATE TABLE book_copy (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_number VARCHAR(50) NOT NULL,
    book_id          BIGINT      NOT NULL REFERENCES book (id),
    library_id       BIGINT      NOT NULL REFERENCES library (id),
    CONSTRAINT uk_book_copy_inventory_number UNIQUE (inventory_number)
);
-- serves the "max 5 copies per (library, book)" count query
CREATE INDEX ix_book_copy_library_book ON book_copy (library_id, book_id);
CREATE INDEX ix_book_copy_book ON book_copy (book_id);
--rollback DROP TABLE book_copy;
